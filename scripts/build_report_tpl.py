def set_font(run, ea="宋体", size=12, bold=False, ascii_font="Times New Roman"):
    run.font.size = Pt(size)
    run.font.bold = bold
    run.font.name = ascii_font
    rpr = run._element.get_or_add_rPr()
    rf = rpr.find(qn("w:rFonts"))
    if rf is None:
        rf = OxmlElement("w:rFonts")
        rpr.insert(0, rf)
    rf.set(qn("w:eastAsia"), ea)
    rf.set(qn("w:ascii"), ascii_font)
    rf.set(qn("w:hAnsi"), ascii_font)


def p_body(doc, text, size=12, indent=True, align=None, ea="宋体"):
    p = doc.add_paragraph()
    pf = p.paragraph_format
    pf.line_spacing = 1.5
    pf.space_after = Pt(0)
    if indent and align is None:
        pf.first_line_indent = Cm(0.85)
    if align is not None:
        p.alignment = align
    set_font(p.add_run(text), ea=ea, size=size)
    return p


