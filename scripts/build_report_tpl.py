def _set_tbl_borders(tbl):
    """手工给表格加单线边框（模板没有 Table Grid 样式，不能依赖样式名）。"""
    tblPr = tbl._element.tblPr
    borders = OxmlElement("w:tblBorders")
    for edge in ("top", "left", "bottom", "right", "insideH", "insideV"):
        el = OxmlElement("w:" + edge)
        el.set(qn("w:val"), "single")
        el.set(qn("w:sz"), "4")
        el.set(qn("w:space"), "0")
        el.set(qn("w:color"), "000000")
        borders.append(el)
    tblPr.append(borders)


def add_table(doc, headers, rows, widths=None, cap=None):
    t = doc.add_table(rows=1, cols=len(headers))
    _set_tbl_borders(t)
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for i, h in enumerate(headers):
        c = t.rows[0].cells[i]
        c.text = ""
        cp = c.paragraphs[0]
        cp.alignment = WD_ALIGN_PARAGRAPH.CENTER
        set_font(cp.add_run(str(h)), ea="黑体", size=10.5, bold=True)
    for row in rows:
        cells = t.add_row().cells
        for i, v in enumerate(row):
            cells[i].text = ""
            cp = cells[i].paragraphs[0]
            cp.paragraph_format.space_after = Pt(0)
            set_font(cp.add_run("" if v is None else str(v)), ea="宋体", size=10.5)
    if widths:
        for i, w in enumerate(widths):
            for r in t.rows:
                r.cells[i].width = Cm(w)
    if cap:
        p_caption(doc, cap)
    else:
        doc.add_paragraph()
    return t


