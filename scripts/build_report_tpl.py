def insert_toc_field(doc):
    """插入 Word 原生目录域（用户按 F9 即可生成带页码的目录）。"""
    p = doc.add_paragraph()
    r = p.add_run()
    fld_begin = OxmlElement("w:fldChar")
    fld_begin.set(qn("w:fldCharType"), "begin")
    instr = OxmlElement("w:instrText")
    instr.set(qn("xml:space"), "preserve")
    instr.text = r'TOC \o "1-3" \h \z \u'
    fld_sep = OxmlElement("w:fldChar")
    fld_sep.set(qn("w:fldCharType"), "separate")
    placeholder = OxmlElement("w:t")
    placeholder.text = "（在此按 F9 或右键“更新域”生成目录）"
    fld_end = OxmlElement("w:fldChar")
    fld_end.set(qn("w:fldCharType"), "end")
    r._element.append(fld_begin)
    r._element.append(instr)
    r._element.append(fld_sep)
    r._element.append(placeholder)
    r._element.append(fld_end)
    return p


