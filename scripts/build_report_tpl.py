    copy_cover_from_template(doc)
    fill_cover_text(doc)

    build_front(doc)
    build_ch1(doc)
    build_ch2(doc)
    build_ch3(doc)
    build_ch4(doc)
    build_ch5(doc)
    build_ch6(doc)
