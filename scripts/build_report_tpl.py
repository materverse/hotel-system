def reindex_headings(doc):
    """设置大纲级别，保证 Word 目录域能抓到标题。"""
    lv = {}
    for p in doc.paragraphs:
        txt = p.text.strip()
        m = None
        if txt and p.runs:
            sz = p.runs[0].font.size
            ea = None
            rpr = p.runs[0]._element.find(qn("w:rPr"))
            if rpr is not None:
                rf = rpr.find(qn("w:rFonts"))
                if rf is not None:
                    ea = rf.get(qn("w:eastAsia"))
            if ea == "黑体" and sz is not None:
                if sz.pt >= 18:
                    m = 1
                elif sz.pt >= 15:
                    m = 2
                elif sz.pt >= 14:
                    m = 3
        if m:
            ppr = p._element.get_or_add_pPr()
            if ppr.find(qn("w:outlineLvl")) is None:
                el = OxmlElement("w:outlineLvl")
                el.set(qn("w:val"), str(m - 1))
                ppr.append(el)


def update_toc_with_word(path):
    """用 Word 打开文档，更新目录域（生成真实目录 + 页码）并保存，同时导出 PDF。"""
    try:
        import win32com.client as win32
    except ImportError:
        print("未安装 pywin32，跳过目录自动更新；请在 Word 里按 Ctrl+A 后 F9 手动更新")
        return False
    word = None
    try:
        word = win32.Dispatch("Word.Application")
        word.Visible = False
        word.DisplayAlerts = 0
        doc = word.Documents.Open(path)
        # 更新所有目录
        for i in range(1, doc.TablesOfContents.Count + 1):
            doc.TablesOfContents(i).Update()
        doc.Fields.Update()
        doc.Repaginate()
        pages = doc.ComputeStatistics(2)      # wdStatisticPages
        doc.Save()
        pdf = path.replace(".docx", ".pdf")
        doc.SaveAs2(pdf, FileFormat=17)       # wdFormatPDF
        doc.Close(False)
        print("目录已更新，报告共 %d 页，PDF 已导出" % pages)
        return True
    except Exception as e:
        print("Word 更新目录失败：%s" % e)
        print("请手动打开 Word，全选后按 F9 更新目录")
        return False
    finally:
        if word is not None:
            try:
                word.Quit()
            except Exception:
                pass


